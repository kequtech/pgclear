import { connect } from '../connection/index.js';
import { defaultCodecs, registry } from '../codecs/index.js';
import { validateOperation } from '../config/index.js';
import { Lifetime } from '../connection/timing.js';
import { configurationError } from '../errors.js';
import { executorScope } from '../session/index.js';
import type {
  Connection,
  ConnectionOptions,
  OperationOptions,
  Pool,
  QueryResult,
  Row,
  Session,
} from '../types.js';
import { readTables, type CatalogClient } from './catalog.js';
import { domainSummaries, quote, schemaSummary, tableSummary } from './schema-summary.js';
import { renderDatabase } from './render.js';

export interface GenerateOptions extends OperationOptions {
  /** Supplied pools/sessions are borrowed. Configuration opens a short-lived owned connection. */
  readonly connection: string | ConnectionOptions | Pool | Session;
  readonly namespace?: string;
  /** Consumer-owned tables, such as migration history, may be omitted explicitly. */
  readonly excludeTables?: readonly string[];
  readonly onWarning?: (message: string) => void | Promise<void>;
}

function name(value: unknown): string {
  if (typeof value !== 'string' || !value || value.includes('\0') || !value.isWellFormed())
    configurationError('Expected a nonempty PostgreSQL name without NUL.');
  return value;
}

/** Generate schema types from a read-only snapshot. No files, migrations or query checking. */
export async function generateDefinitions(options: GenerateOptions): Promise<string> {
  validateOperation(options, ['connection', 'namespace', 'excludeTables', 'onWarning']);
  const namespace = options.namespace === undefined ? 'public' : name(options.namespace);
  if (options.excludeTables !== undefined && !Array.isArray(options.excludeTables))
    configurationError('excludeTables must be an array of table names.');
  const exclude = Array.from(options.excludeTables ?? [], name);
  if (options.connection === undefined || options.connection === null)
    configurationError('Generation requires a connection, pool or session.');
  if (options.onWarning !== undefined && typeof options.onWarning !== 'function')
    configurationError('onWarning must be a function.');
  const warn = options.onWarning ?? ((message: string) => console.warn('Warning: ' + message));
  const life = new Lifetime(options);
  let owned: Connection | undefined;
  let failed = false;
  let failure: unknown;
  try {
    life.check();
    const supplied = options.connection;
    let source: Pool | Session;
    if (supplied && typeof supplied === 'object' && 'transaction' in supplied) {
      if (typeof supplied.transaction !== 'function')
        configurationError('Expected a pgclear pool or session.');
      source = supplied as Pool | Session;
    } else source = owned = await connect(supplied, { signal: life.signal });
    return await source.transaction(
      async (tx) => {
        const scope = executorScope(tx);
        // Catalog control values use native defaults even when application columns use overrides.
        const client: CatalogClient = {
          query<T extends object = Row>(text: string, values = []) {
            return scope.call(() =>
              scope.connection.query([text, values], scope.options({}), registry(defaultCodecs)),
            ) as Promise<QueryResult<T>>;
          },
        };
        const schema = await client.query(
          'SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = $1',
          [namespace],
        );
        if (!schema.rows.length) throw new Error(`Schema ${quote(namespace)} does not exist.`);
        await client.query(`SET LOCAL search_path TO pg_catalog, ${quote(namespace)}`);
        await client.query('SET LOCAL quote_all_identifiers TO off');
        await client.query('SET LOCAL standard_conforming_strings TO on');
        const tables = await readTables(client, namespace, exclude);
        const summaries = [];
        for (const table of tables)
          summaries.push(await tableSummary(client, table.oid, table.name));
        const domains = await domainSummaries(
          client,
          tables.flatMap((table) => table.columns.map((column) => column.declaredOid)),
        );
        const warnings: string[] = [];
        const types = renderDatabase(tables, namespace, scope.connection.codecs, (message) =>
          warnings.push(message),
        );
        for (const warning of warnings) {
          life.check();
          scope.check();
          await warn(warning);
        }
        life.check();
        return `// Generated by pgclear from the PostgreSQL schema. Do not edit.\n\n${schemaSummary([...domains, ...summaries])}${types}`;
      },
      { isolation: 'repeatable read', readOnly: true, signal: life.signal },
    );
  } catch (error) {
    failed = true;
    failure = error;
    throw error;
  } finally {
    life.stop();
    if (owned) {
      try {
        await owned.close();
      } catch (cleanup) {
        if (failed)
          throw new AggregateError([failure, cleanup], 'Generation and connection cleanup failed.');
        throw cleanup;
      }
    }
  }
}
